using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

using NUnit.Framework;

namespace NuciCraft.API.ArchitectureTests
{
    internal sealed class SourceProject
    {
        internal static readonly string RepositoryRoot = Path.GetFullPath(
            typeof(SourceProject).Assembly.GetCustomAttributes<AssemblyMetadataAttribute>()
                .Single(attribute => string.Equals(attribute.Key, "RepositoryRoot", StringComparison.Ordinal)).Value!);

        internal static readonly SourceProject[] All =
        [
            new("NuciCraft.API"),
            new("NuciCraft.API.ArchitectureTests"),
            new("NuciCraft.API.IntegrationTests"),
            new("NuciCraft.API.UnitTests")
        ];

        internal string Name { get; }

        internal string DirectoryPath { get; }

        internal CSharpCompilation Compilation { get; }

        internal IEnumerable<SyntaxTree> Trees => Compilation.SyntaxTrees;

        private SourceProject(string name)
        {
            Name = name;
            DirectoryPath = Path.Combine(RepositoryRoot, name);
            Assert.That(Directory.Exists(DirectoryPath), $"Required CI sources are missing: {DirectoryPath}.");
            SyntaxTree[] trees = [.. Directory.EnumerateFiles(DirectoryPath, "*.cs", SearchOption.AllDirectories)
                .Where(IsHandwritten)
                .Select(path => CSharpSyntaxTree.ParseText(
                    File.ReadAllText(path),
                    new CSharpParseOptions(LanguageVersion.Latest),
                    path))
                .Where(tree => !IsGenerated(tree))];
            Assert.That(trees, Is.Not.Empty, $"No handwritten sources found in {DirectoryPath}.");
            Compilation = CSharpCompilation.Create(
                name,
                trees,
                BuildReferences(),
                new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        }

        internal static IEnumerable<TestCaseData> Files()
            => All.SelectMany(project => project.Trees.Select(tree => new TestCaseData(project, tree)
                .SetName($"{{m}}({Path.GetRelativePath(RepositoryRoot, tree.FilePath)})")));

        internal static string Location(SyntaxNode node)
            => $"{Path.GetRelativePath(RepositoryRoot, node.SyntaxTree.FilePath)}:" +
                $"{node.GetLocation().GetLineSpan().StartLinePosition.Line + 1}";

        internal static string TypeName(MemberDeclarationSyntax declaration)
        {
            if (declaration is BaseTypeDeclarationSyntax type)
            {
                return type.Identifier.ValueText;
            }

            return ((DelegateDeclarationSyntax)declaration).Identifier.ValueText;
        }

        private static bool IsHandwritten(string path)
            => !Path.GetRelativePath(RepositoryRoot, path).Split(Path.DirectorySeparatorChar)
                .Any(segment => segment is "bin" or "obj") &&
                !path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) &&
                !path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase) &&
                !path.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase);

        private static bool IsGenerated(SyntaxTree tree)
            => tree.GetRoot().GetLeadingTrivia().Any(trivia =>
                trivia.ToString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase));

        private static IEnumerable<MetadataReference> BuildReferences()
        {
            string? trustedAssemblies = AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") as string;
            Assert.That(trustedAssemblies, Is.Not.Null.And.Not.Empty, "Runtime reference inventory is unavailable.");
            IEnumerable<string> paths = trustedAssemblies!.Split(Path.PathSeparator)
                .Concat(Directory.GetFiles(TestContext.CurrentContext.TestDirectory, "*.dll"))
                .Where(path => !string.Equals(
                    Path.GetFileNameWithoutExtension(path),
                    "NuciCraft.API.ArchitectureTests",
                    StringComparison.Ordinal));

            return paths.Distinct(StringComparer.Ordinal).Select(path => MetadataReference.CreateFromFile(path));
        }
    }
}